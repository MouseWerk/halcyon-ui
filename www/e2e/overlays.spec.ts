import { test, expect, openComponent, go } from "./fixtures"

test("dialog opens, traps focus, locks scroll and closes on Escape", async ({ page }) => {
  const demo = await openComponent(page, "dialog")
  await demo.getByRole("button", { name: "Delete workspace" }).click()
  const dialog = page.getByRole("dialog")
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveAccessibleName("Delete this workspace?")
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe("hidden")
  // the confirm button is disabled until the name is typed
  const confirm = dialog.getByRole("button", { name: "Delete workspace" })
  await expect(confirm).toBeDisabled()
  await dialog.getByRole("textbox").fill("Halcyon Labs")
  await expect(confirm).toBeEnabled()
  await page.keyboard.press("Escape")
  await expect(dialog).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe("")
})

test("a select inside a sheet closes on its own, the sheet stays open", async ({ page }) => {
  const demo = await openComponent(page, "sheet")
  await demo.getByRole("button", { name: "Open right" }).click()
  const sheet = page.getByRole("dialog")
  await expect(sheet).toBeVisible()
  await sheet.getByRole("combobox", { name: "Plan" }).click()
  const list = page.getByRole("listbox")
  await expect(list).toBeVisible()
  await list.getByRole("option", { name: "Pro" }).click()
  await expect(list).toBeHidden()
  await expect(sheet).toBeVisible()
  await expect(sheet.getByRole("combobox", { name: "Plan" })).toContainText("Pro")
  // Escape with the list open closes only the list
  await sheet.getByRole("combobox", { name: "Plan" }).click()
  await expect(page.getByRole("listbox")).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("listbox")).toBeHidden()
  await expect(sheet).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(sheet).toBeHidden()
  expect(await page.evaluate(() => document.documentElement.style.overflow)).toBe("")
})

test("dropdown menu works with the keyboard and returns focus", async ({ page }, info) => {
  test.skip(info.project.name.startsWith("phone") || info.project.name === "tablet", "keyboard flow")
  const demo = await openComponent(page, "dropdown-menu")
  const trigger = demo.getByRole("button").first()
  await trigger.click()
  const menu = page.getByRole("menu")
  await expect(menu).toBeVisible()
  await expect(menu).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await page.keyboard.press("Escape")
  await expect(menu).toBeHidden()
  await expect(trigger).toBeFocused()
})

test("popover and tooltip open and close", async ({ page }) => {
  const demo = await openComponent(page, "popover")
  await demo.getByRole("button", { name: "Share" }).click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await page.mouse.click(5, 5)
  await expect(page.getByRole("dialog")).toBeHidden()

  const tip = await openComponent(page, "tooltip")
  await tip.getByRole("button").first().focus()
  await expect(page.getByRole("tooltip")).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("tooltip")).toBeHidden()
})

test("command palette opens with Ctrl/Cmd+K and navigates", async ({ page }, info) => {
  test.skip(info.project.name.startsWith("phone") || info.project.name === "tablet", "hardware keyboard")
  await go(page, "/docs")
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible()
  await page.keyboard.press("ControlOrMeta+k")
  const input = page.getByRole("dialog").getByRole("combobox")
  await expect(input).toBeFocused()
  await input.fill("knob")
  await page.keyboard.press("Enter")
  await expect(page).toHaveURL(/#\/docs\/components\/knob$/)
  await expect(page.getByRole("heading", { level: 1, name: "Knob" })).toBeVisible()
})

test("toast springs in and leaves", async ({ page }) => {
  const demo = await openComponent(page, "toast")
  await demo.getByRole("button").first().click()
  const t = page.locator('section[aria-label="Notifications"] li').first()
  await expect(t).toBeVisible()
  await expect(t).toHaveCSS("opacity", "1")
  await expect(t).toBeHidden({ timeout: 8000 })
})

test("toast action, description and promise", async ({ page }) => {
  const demo = await openComponent(page, "toast")
  const region = page.locator('section[aria-label="Notifications"]')
  await demo.getByRole("button", { name: "Error toast" }).click()
  await expect(region).toContainText("3 retries left")
  await demo.getByRole("button", { name: "With action" }).click()
  await region.getByRole("button", { name: "Undo" }).click()
  await expect(region).toContainText("Restored")
  await demo.getByRole("button", { name: "Promise" }).click()
  await expect(region).toContainText("Deploying...")
  await expect(region).toContainText("Deployed to production", { timeout: 5000 })
})
